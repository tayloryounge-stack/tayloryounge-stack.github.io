function applyLanguage(lang) {
  const dictionary = translations[lang] || translations['zh'];
  
  // Update texts based on data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      // Use innerHTML for keys that might contain HTML (like hero-title, hero-desc, btn-visit, status-brewing)
      if (key === 'hero-title' || key === 'hero-desc' || key === 'btn-visit' || key === 'status-brewing' || key === 'phil-desc') {
        element.innerHTML = dictionary[key];
      } else {
        element.textContent = dictionary[key];
      }
    }
  });

  // Update specific elements like title and meta description
  if (dictionary['page-title']) {
    document.title = dictionary['page-title'];
  }
  if (dictionary['meta-desc']) {
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', dictionary['meta-desc']);
  }
  
  // Update HTML lang attribute
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}

document.addEventListener('DOMContentLoaded', () => {
  // Detect system language
  const userLang = navigator.language || navigator.userLanguage;
  const langCode = userLang.startsWith('zh') ? 'zh' : 'en';
  
  // Apply the detected language
  applyLanguage(langCode);
});
